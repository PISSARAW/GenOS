use clap::Args;

/// `genos run --mode trinity --monitor` launches the native TUI monitor that
/// attaches to a live Trinity mission over the `trinityMonitorServer.js`
/// NDJSON socket, mapping the 3 isolated worlds and the evidence barrier onto
/// the ratatui split-screen.
#[derive(Args, Debug)]
pub struct RunCmd {
    /// Mission text; routes to the backend orchestrator when provided.
    #[arg(value_name = "MISSION", conflicts_with = "mission_option")]
    pub mission: Option<String>,
    /// Mission text using the documented long option form.
    #[arg(long = "mission", value_name = "MISSION", conflicts_with = "mission")]
    pub mission_option: Option<String>,
    /// Existing workspace directory used for read-only mission execution.
    #[arg(long, value_name = "PATH")]
    pub workspace_root: Option<std::path::PathBuf>,
    /// Caller-supplied homeostasis completion contract JSON; never generated by the CLI.
    #[arg(long, value_name = "JSON")]
    pub completion_contract: Option<String>,
    /// Caller-supplied non-empty JSON array of mission success criteria.
    #[arg(long, value_name = "JSON")]
    pub success_criteria: Option<String>,
    /// Caller-supplied native worker objectives; each requires a goal, criteria, and versioned method contract.
    #[arg(long, value_name = "JSON")]
    pub native_objectives: Option<String>,
    /// Opt in to hashing read-only workspace files as worker evidence.
    #[arg(long, default_value_t = false)]
    pub read_only_workspace_evidence: bool,
    /// Bounded mission deadline in milliseconds (1,000 to 180,000).
    #[arg(long, default_value_t = 180_000, value_parser = clap::value_parser!(u64).range(1_000..=180_000))]
    pub timeout_ms: u64,
    /// Executor required by the independent Rust verifier; local mode lacks worker receipts.
    #[arg(long, default_value = "codex", value_parser = ["codex"])]
    pub executor: String,
    /// Execution mode to run. Currently supports: trinity
    #[arg(long, default_value = "trinity")]
    pub mode: String,
    /// Attach the native TUI monitor to a live mission instead of running the
    /// scripted demo narrative.
    #[arg(long)]
    pub monitor: bool,
    /// Mission id to subscribe to. Defaults to the most recently deployed mission.
    #[arg(long)]
    pub mission_id: Option<String>,
    /// Trinity monitor server host (see GENOS_TRINITY_MONITOR_PORT on the backend).
    #[arg(long, default_value = "127.0.0.1")]
    pub host: String,
    /// Trinity monitor server TCP port.
    #[arg(long, default_value_t = 4590)]
    pub port: u16,
    /// Target prompt / engineering goal, used only when --monitor is not set (demo mode).
    #[arg(long, short = 'p')]
    pub prompt: Option<String>,
    /// Run scripted simulation demo rather than connecting live
    #[arg(long, default_value_t = false)]
    pub simulation: bool,
}

#[cfg(test)]
mod tests {
    use clap::Parser;

    use crate::args::{Cli, Commands};

    #[test]
    fn run_accepts_positional_and_long_mission_forms() {
        assert_mission(&["genos", "run", "positional task"], "positional task");
        assert_mission(&["genos", "run", "--mission", "flag task"], "flag task");
    }

    #[test]
    fn run_accepts_explicit_workspace_contract_and_success_criteria() {
        let parsed = Cli::try_parse_from([
            "genos", "run", "--mission", "task", "--workspace-root", "workspace",
            "--completion-contract", r#"{"invariants":[]}"#,
            "--success-criteria", r#"["cargo test passes"]"#,
            "--native-objectives", r#"[{"goal":"inspect","successCriteria":["cite result"],"methodContract":{"version":1,"methodId":"scan_literal","parameters":{}}}]"#,
            "--read-only-workspace-evidence",
        ]).expect("CLI options should parse");
        match parsed.command {
            Some(Commands::Run(command)) => {
                assert_eq!(command.workspace_root.unwrap(), std::path::PathBuf::from("workspace"));
                assert_eq!(command.completion_contract.as_deref(), Some(r#"{"invariants":[]}"#));
                assert_eq!(command.success_criteria.as_deref(), Some(r#"["cargo test passes"]"#));
                assert!(command.native_objectives.as_deref().unwrap().contains("scan_literal"));
                assert!(command.read_only_workspace_evidence);
                assert_eq!(command.timeout_ms, 180_000);
                assert_eq!(command.executor, "codex");
            }
            _ => panic!("expected run command"),
        }
    }

    #[test]
    fn run_rejects_timeout_values_outside_the_bounded_range() {
        assert!(Cli::try_parse_from(["genos", "run", "task", "--timeout-ms", "0"]).is_err());
        assert!(Cli::try_parse_from(["genos", "run", "task", "--timeout-ms", "180001"]).is_err());
    }

    #[test]
    fn run_rejects_executor_without_durable_worker_receipts() {
        assert!(Cli::try_parse_from(["genos", "run", "task", "--executor", "local"]).is_err());
    }


    #[test]
    fn run_rejects_two_mission_values() {
        assert!(
            Cli::try_parse_from(["genos", "run", "positional task", "--mission", "flag task"])
                .is_err()
        );
    }

    fn assert_mission(arguments: &[&str], expected: &str) {
        let parsed = Cli::try_parse_from(arguments).expect("mission syntax should parse");
        match parsed.command {
            Some(Commands::Run(command)) => {
                assert_eq!(
                    command.mission.or(command.mission_option).as_deref(),
                    Some(expected)
                );
            }
            _ => panic!("expected run command"),
        }
    }
}
