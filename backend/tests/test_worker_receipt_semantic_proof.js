'use strict';
const assert = require('node:assert/strict');
const { semanticProofAccepted } = require('../src/services/biologicalWorkerReceiptService');
const { semanticReceiptAccepted } = require('../src/services/biologicalWorkerReceiptService');
const verification = (domain, accepted = true) => ({ proof: { attestation: { value: { domain, accepted } } } });
assert.equal(semanticProofAccepted(null), false);
assert.equal(semanticProofAccepted(verification('worker_artifact')), false);
assert.equal(semanticProofAccepted(verification('model_subset_sum', false)), false);
assert.equal(semanticProofAccepted(verification('unknown')), false);
assert.equal(semanticProofAccepted(verification('model_subset_sum')), true);
assert.equal(semanticReceiptAccepted(undefined), false, 'legacy receipts without a semantic domain remain unverified');
assert.equal(semanticReceiptAccepted({ domain: 'worker_artifact', accepted: true }), false);
assert.equal(semanticReceiptAccepted({ domain: 'model_subset_sum', accepted: true }), false);
const semanticReceipt = { domain: 'model_subset_sum', accepted: true, hash: 'hash', eventId: 'event', acceptanceHash: 'acceptance' };
assert.equal(semanticReceiptAccepted(semanticReceipt), true);
const { proofFromRow } = require('../src/services/missionCompletionEvidenceService');
const { digest } = require('../src/services/biologicalIntegrity');
const legacy = { result: { status: 'completed', verified: true } };
const row = value => ({ receipt_json: JSON.stringify(value), payload_hash: digest(value) });
assert.equal(proofFromRow(row(legacy)), null, 'legacy execution receipts cannot prove a mission result');
assert.ok(proofFromRow(row({ ...legacy, semanticVerification: semanticReceipt })));
console.log('Worker receipt semantic proof: PASS');
